"""Non-inverse-crime validation for the (1, 4, 1)/6 deconvolution operator.

The DRO recovery tests in ``test_dsc_recovery.py`` build the tissue curve with
``build_block_circulant_matrix``/``build_toeplitz_matrix`` and then invert the
*same* operator, so they prove self-consistency but cannot validate the
quadrature itself. Here the tissue curve is generated by an INDEPENDENT
fine-grid physical convolution (``np.convolve`` on a dt/20 grid, downsampled to
frames) that never touches the deconvolution matrices, then deconvolved with the
production oSVD operator. This confirms the (1, 4, 1)/6 quadrature recovers both
CBF and the shipped residue MTT within physical bounds on data the operator did
not create.

Tolerances are the realistic non-inverse-crime accuracy of oSVD at clinical TR
with a sharp arterial AIF (worse than the inverse-crime DRO): CBF and MTT each
underestimated ~10-19%, the known SVD-deconvolution regime. The residue MTT
(int R / max R) cancels the CBF scaling, so it stays accurate (~-10%) despite
the larger CBF underestimate -- this is why production ships the residue MTT
rather than AUC-CBV / CBF (which would propagate the CBF bias into MTT).
"""
import numpy as np
import pytest
from scipy.linalg import svd

from pmriprep.utils.dsc_deconvolution import (
    build_toeplitz_matrix,
    build_volterra_matrix,
    svd_deconvolve_oscillation,
    svd_deconvolve_standard,
    tikhonov_deconvolve,
)
from pmriprep.utils.dsc_constants import DEFAULT_SVD_THRESHOLD


def _gamma_aif(t, t0=10.0, alpha=3.0, beta=1.5, peak=4.0):
    a = np.zeros_like(t)
    m = t > t0
    a[m] = ((t[m] - t0) ** alpha) * np.exp(-(t[m] - t0) / beta)
    return a / a.max() * peak if a.max() > 0 else a


def _independent_tissue(aif, cbf, mtt, dt, oversample=20):
    """C(t) = CBF * int_0^t AIF(tau) exp(-(t-tau)/MTT) dtau on a fine grid.

    Generated by ``np.convolve`` at dt/oversample then downsampled to frames,
    so the tissue curve is NOT produced by the deconvolution's own matrix.
    """
    n = len(aif)
    fine_dt = dt / oversample
    n_fine = n * oversample
    t_fine = np.arange(n_fine) * fine_dt
    t_frame = np.arange(n) * dt
    aif_fine = np.interp(t_fine, t_frame, aif)
    residue_fine = np.exp(-t_fine / mtt)  # R(0) = 1
    conv = np.convolve(aif_fine, residue_fine)[:n_fine] * fine_dt
    return cbf * conv[::oversample]


TISSUES = [("GM", 60.0, 4.0), ("WM", 25.0, 4.8), ("Tumor", 100.0, 6.0)]


@pytest.mark.parametrize("name,cbf_true,mtt_true", TISSUES)
def test_osvd_recovers_independent_tissue(name, cbf_true, mtt_true):
    """oSVD (default) recovers CBF and residue-MTT from physically-convolved tissue.

    CBF and MTT each within the known SVD-deconvolution underestimation regime
    at clinical TR with a sharp arterial AIF (measured: CBF -10 to -19%, residue
    MTT -9 to -11%). The residue MTT staying near -10% while CBF is off by up to
    -19% demonstrates the CBF-scaling cancellation that motivates shipping the
    residue MTT rather than AUC-CBV / CBF.
    """
    dt = 1.5
    n = 60
    t = np.arange(n) * dt
    aif = _gamma_aif(t)
    tissue = _independent_tissue(aif, cbf_true, mtt_true, dt)

    res = svd_deconvolve_oscillation(tissue, aif, dt=dt)

    cbf_err = (res.cbf - cbf_true) / cbf_true
    assert -0.25 < cbf_err < 0.10, f"{name} oSVD CBF error {cbf_err:.1%}"

    mtt_err = (res.mtt - mtt_true) / mtt_true
    assert -0.20 < mtt_err < 0.10, f"{name} oSVD residue-MTT error {mtt_err:.1%}"


def _ssvd_cbf_with_operator(tissue, aif, dt, builder, threshold):
    """Truncated-SVD CBF using an explicit forward operator.

    Mirrors :func:`svd_deconvolve_standard`'s math so the Volterra and Toeplitz
    operators can be compared head to head on identical tissue.
    """
    A = builder(aif, dt)
    u, s, vh = svd(A, full_matrices=False)
    s_inv = np.where(s > threshold * s.max(), 1.0 / s, 0.0)
    residue = vh.T @ (s_inv * (u.T @ tissue))
    return float(np.max(residue))


@pytest.mark.parametrize("name,cbf_true,mtt_true", TISSUES)
def test_ssvd_recovers_independent_tissue(name, cbf_true, mtt_true):
    """sSVD (Volterra) recovers CBF and residue-MTT from physically-convolved tissue.

    Non-inverse-crime accuracy of the production sSVD with a sharp arterial AIF
    at clinical TR (measured: CBF -8 to -18%, the known SVD underestimation
    regime; residue-MTT within [-15%, +40%]).
    """
    dt, n = 1.5, 60
    t = np.arange(n) * dt
    aif = _gamma_aif(t)
    tissue = _independent_tissue(aif, cbf_true, mtt_true, dt)

    res = svd_deconvolve_standard(tissue, aif, dt=dt)

    cbf_err = (res.cbf - cbf_true) / cbf_true
    assert -0.30 < cbf_err < 0.10, f"{name} sSVD CBF error {cbf_err:.1%}"
    mtt_err = (res.mtt - mtt_true) / mtt_true
    assert -0.15 < mtt_err < 0.40, f"{name} sSVD residue-MTT error {mtt_err:.1%}"


@pytest.mark.parametrize("name,cbf_true,mtt_true", TISSUES)
def test_ssvd_volterra_beats_toeplitz(name, cbf_true, mtt_true):
    """The Volterra operator recovers CBF closer to truth than smoothed-Toeplitz.

    The can-fail thesis for the operator migration: on independent
    (non-inverse-crime) tissue, the production Volterra sSVD must beat the old
    smoothed-Toeplitz sSVD per tissue, or the change does not belong in
    production.
    """
    dt, n = 1.5, 60
    t = np.arange(n) * dt
    aif = _gamma_aif(t)
    tissue = _independent_tissue(aif, cbf_true, mtt_true, dt)
    thr = DEFAULT_SVD_THRESHOLD

    cbf_volterra = _ssvd_cbf_with_operator(tissue, aif, dt, build_volterra_matrix, thr)
    cbf_toeplitz = _ssvd_cbf_with_operator(tissue, aif, dt, build_toeplitz_matrix, thr)
    err_v = abs(cbf_volterra - cbf_true) / cbf_true
    err_t = abs(cbf_toeplitz - cbf_true) / cbf_true

    assert err_v < err_t, (
        f"{name}: Volterra CBF err {err_v:.1%} not < Toeplitz {err_t:.1%}"
    )


@pytest.mark.parametrize("name,cbf_true,mtt_true", TISSUES)
def test_tikhonov_recovers_independent_tissue(name, cbf_true, mtt_true):
    """Tikhonov (Volterra + Morozov) recovers CBF from physically-convolved tissue.

    Noise-free accuracy of the production Tikhonov on independent tissue: with no
    measurable noise floor the degenerate fallback applies a small fixed λ, which
    keeps the noise-free CBF within a few percent of truth (measured ~0-3%).
    """
    dt, n = 1.5, 60
    t = np.arange(n) * dt
    aif = _gamma_aif(t)
    tissue = _independent_tissue(aif, cbf_true, mtt_true, dt)

    res = tikhonov_deconvolve(tissue, aif, dt=dt)

    cbf_err = (res.cbf - cbf_true) / cbf_true
    assert -0.15 < cbf_err < 0.10, f"{name} Tikhonov CBF error {cbf_err:.1%}"


@pytest.mark.parametrize("name,cbf_true,mtt_true", TISSUES)
def test_auc_cbv_recovers_independent_tissue(name, cbf_true, mtt_true):
    """AUC-CBV (∫tissue / ∫aif, trapezoidal) recovers CBV = CBF·MTT.

    Neutral accuracy anchor for the AUC-CBV path (previously untested in-repo by
    any code-generated DRO): the tissue curve comes from the dt/20 fine-grid
    forward, so the production trapezoidal ratio is validated against a truth it
    did not generate. Exercises the convolution-area identity
    ∫(AIF ⊗ R) = ∫AIF · ∫R that AUC-CBV relies on; the only error source is the
    tissue-tail truncation at the 90 s window, which is sub-percent for MTT ≤ 6 s.
    """
    dt, n = 1.5, 60
    t = np.arange(n) * dt
    aif = _gamma_aif(t)
    tissue = _independent_tissue(aif, cbf_true, mtt_true, dt)

    cbv_true = cbf_true * mtt_true
    cbv_est = float(np.trapezoid(tissue, dx=dt) / np.trapezoid(aif, dx=dt))
    rel = (cbv_est - cbv_true) / cbv_true
    assert abs(rel) < 0.02, (
        f"{name} AUC-CBV {cbv_est:.1f} vs true {cbv_true:.1f} ({rel:+.1%})"
    )
